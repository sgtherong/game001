  const LANGS = ['en', 'ko', 'es', 'pt', 'ru', 'de', 'fr'];
  const LS_KEY = 'bm_lang_v1';
  let lang = 'en';

  function pickInitial() {
    // honor the player's saved choice; else auto-detect the browser language
    // among supported ones; fall back to English if none match
    try { const s = localStorage.getItem(LS_KEY); if (s && S[s]) return s; } catch (e) {}
    const nav = (navigator.languages || [navigator.language || 'en']);
    for (const l of nav) { const code = String(l).slice(0, 2).toLowerCase(); if (S[code]) return code; }
    return 'en';
  }

  function t(key, vars) {
    let str = (S[lang] && S[lang][key]) != null ? S[lang][key] : (S.en[key] != null ? S.en[key] : key);
    if (vars) for (const k in vars) str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    return str;
  }

  function apply(root) {
    (root || document).querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
    (root || document).querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
    (root || document).querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
    document.documentElement.lang = lang;
  }

  window.I18N = {
    langs: LANGS,
    get lang() { return lang; },
    name(code) { return (S[code] && S[code].lang_name) || code; },
    setLang(code) { if (S[code]) { lang = code; try { localStorage.setItem(LS_KEY, code); } catch (e) {} apply(); if (window.onLangChange) window.onLangChange(); } },
    // 포털 사용자 언어(예: "pt-BR")로 맞춘다 — 플레이어가 직접 고른 언어가 있으면 그것을 우선(저장하지 않음)
    adoptLocale(locale) {
      try { if (localStorage.getItem(LS_KEY)) return; } catch (e) {}
      const code = String(locale || '').slice(0, 2).toLowerCase();
      if (S[code]) lang = code;
    },
    t, apply,
  };
  lang = pickInitial();
